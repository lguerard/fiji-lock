def jdk_files(flavor):
    rel = 'IMPLEMENTOR="Azul Systems, Inc."\nJAVA_VERSION="21.0.7"\n'
    exe = ".exe" if flavor.startswith("win") else ""
    home = "zulu-21.jdk/Contents/Home/" if flavor.startswith("macosx") else ""
    return {
        home + "release": (rel, 0o644),
        home + f"bin/java{exe}": (f"java-{flavor}", 0o755),
        home + "lib/modules": (f"modules-{flavor}" * 50, 0o644),
        home + "legal/LICENSE": ("GPLv2+CE", 0o644),
    }


def make_archive(flavor):
    top = f"{ZULU}-{flavor}"
    files = jdk_files(flavor)
    if flavor.startswith("win"):
        with zipfile.ZipFile(cdn / f"{top}.zip", "w") as z:
            for rel, (content, mode) in files.items():
                zi = zipfile.ZipInfo(f"{top}/{rel}")
                zi.external_attr = (0o100000 | mode) << 16
                z.writestr(zi, content)
    else:
        with tarfile.open(cdn / f"{top}.tar.gz", "w:gz") as t:
            for rel, (content, mode) in files.items():
                data = content.encode()
                ti = tarfile.TarInfo(f"{top}/{rel}")
                ti.size, ti.mode = len(data), mode
                t.addfile(ti, io.BytesIO(data))
            if flavor.startswith("macosx"):
                ti = tarfile.TarInfo(f"{top}/bin")
                ti.type, ti.linkname = tarfile.SYMTYPE, "zulu-21.jdk/Contents/Home/bin"
                t.addfile(ti)


