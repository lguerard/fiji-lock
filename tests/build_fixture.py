def jar(path, payload, build="2023-01-01", dup=False):
    """Jar with Maven metadata derived from its name (a-1.2.jar[-timestamp])."""
    path.parent.mkdir(parents=True, exist_ok=True)
    m = re.match(r"(.+?)-(\d[\d.]*)\.jar(-\d+)?$", path.name)
    with zipfile.ZipFile(path, "w") as z:
        z.writestr(
            "META-INF/MANIFEST.MF",
            f"Manifest-Version: 1.0\nBuilt-By: me\nBuild-Date: {build}\n",
        )
        if m:
            a, v = m.group(1), m.group(2)
            z.writestr(
                f"META-INF/maven/org.example/{a}/pom.properties",
                f"#Generated by Maven\n#{build}\ngroupId=org.example\nartifactId={a}\nversion={v}\n",
            )
        z.writestr("x.properties", f"#generated at some date\nv={payload}\n")
        z.writestr("Payload.class", payload)
        if dup:
            z.writestr("Payload.class", payload + "-dup")


def txt(path, s):
    path.parent.mkdir(parents=True, exist_ok=True)
